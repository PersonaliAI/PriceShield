"""PDF Service — handles generation of professional margin audit reports."""

import os
import tempfile
from datetime import datetime
from typing import List, Optional
from fpdf import FPDF
from app.models.invoice import PriceAlert

class PDFService:
    """Generates professional, branded PDF reports for PriceShield users."""

    def __init__(self):
        self.tmp_dir = os.path.join(tempfile.gettempdir(), "reports")
        os.makedirs(self.tmp_dir, exist_ok=True)

    def generate_weekly_report(
        self, 
        user_name: str, 
        timeframe: str, 
        total_loss: float, 
        alerts: List[PriceAlert]
    ) -> str:
        """Create a detailed PDF report and return the file path."""
        pdf = FPDF()
        pdf.add_page()
        
        # --- Header ---
        pdf.set_fill_color(15, 15, 26) # #0f0f1a
        pdf.rect(0, 0, 210, 40, 'F')
        
        pdf.set_font("Arial", 'B', 24)
        pdf.set_text_color(16, 185, 129) # #10b981 (emerald-500)
        pdf.set_xy(10, 10)
        pdf.cell(0, 15, "PriceShield Audit", ln=True)
        
        pdf.set_font("Arial", '', 10)
        pdf.set_text_color(148, 163, 184) # #94a3b8
        pdf.set_xy(10, 22)
        pdf.cell(0, 10, f"{timeframe} Margin Intelligence Report | {datetime.utcnow().strftime('%B %d, %Y')}", ln=True)
        
        # --- Summary Box ---
        pdf.set_xy(10, 50)
        pdf.set_fill_color(248, 113, 113) # #f87171 (rose-400)
        pdf.set_text_color(255, 255, 255)
        pdf.set_font("Arial", 'B', 16)
        pdf.cell(190, 20, f"  TOTAL MARGIN IMPACT: ${total_loss:.2f}", ln=True, fill=True)
        
        pdf.ln(10)
        
        # --- Introduction ---
        pdf.set_text_color(30, 41, 59)
        pdf.set_font("Arial", '', 11)
        pdf.multi_cell(0, 7, f"Hi {user_name},\n\nThis report summarizes all price hikes detected across your supplier invoices for the {timeframe.lower()} period. Each hike represents a stealth increase in your COGS that was caught by our AI engine.")
        
        pdf.ln(5)
        
        # --- Detailed Table ---
        pdf.set_font("Arial", 'B', 12)
        pdf.cell(0, 10, "Supplier Breakdown", ln=True)
        pdf.ln(2)
        
        # Table Header
        pdf.set_fill_color(241, 245, 249)
        pdf.set_font("Arial", 'B', 10)
        pdf.cell(70, 10, "  Supplier", border=1, fill=True)
        pdf.cell(40, 10, "  Date", border=1, fill=True)
        pdf.cell(40, 10, "  Hikes", border=1, fill=True)
        pdf.cell(40, 10, "  Impact", border=1, fill=True)
        pdf.ln()
        
        # Table Content
        pdf.set_font("Arial", '', 10)
        hike_alerts = [a for a in alerts if a.has_hikes]
        
        if not hike_alerts:
            pdf.cell(190, 10, "No price hikes detected in this period. Your margins are safe!", border=1, align='C')
        else:
            for alert in hike_alerts:
                pdf.cell(70, 10, f"  {alert.vendor_name}", border=1)
                pdf.cell(40, 10, f"  {alert.invoice_date}", border=1)
                pdf.cell(40, 10, f"  {len(alert.flagged_items)} items", border=1)
                pdf.set_text_color(220, 38, 38) # Red
                pdf.cell(40, 10, f"  ${alert.total_margin_lost:.2f}", border=1)
                pdf.set_text_color(30, 41, 59) # Reset
                pdf.ln()
        
        pdf.ln(10)
        
        # --- Footer ---
        pdf.set_font("Arial", 'I', 8)
        pdf.set_text_color(148, 163, 184)
        pdf.cell(0, 10, "Generated by PriceShield AI | Confidential Business Intelligence", align='C')
        
        # Save file
        filename = f"PriceShield_Report_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.pdf"
        filepath = os.path.join(self.tmp_dir, filename)
        pdf.output(filepath)
        
        return filepath
